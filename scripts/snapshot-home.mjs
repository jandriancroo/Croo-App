#!/usr/bin/env node
// Crawler-readable homepage snapshot.
// Renders the real built homepage (dist/, via `vite preview`) in a FRESH, logged-out
// headless Chromium context (no profile, cookies, or localStorage), extracts a
// text-only semantic copy of <Home/> (headings, copy, links; no styles/images/scripts),
// and writes seo/home-snapshot.html. vite.config.ts injects that file into index.html
// inside #root at build time (React's createRoot replaces it on mount; an inline
// script hides it on every route other than "/").
// Usage: npm run build && npm run snapshot:home && npm run build   (see seo/README.md)
// Needs playwright resolvable (e.g. NODE_PATH pointing at a dir with `npm i playwright`).
import fs from "node:fs"; import path from "node:path"; import { spawn } from "node:child_process";
import { createRequire } from "node:module";
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const OUT = path.join(ROOT, "seo/home-snapshot.html");
const req = createRequire(path.join(process.env.NODE_PATH || ROOT, "x.js"));
const { chromium } = req("playwright");
const PORT = 4791;
const srv = spawn("npx", ["vite", "preview", "--port", String(PORT), "--strictPort"], { cwd: ROOT, stdio: "ignore" });
const sleep = ms => new Promise(r => setTimeout(r, ms));
try {
  let up = false;
  for (let i = 0; i < 60 && !up; i++) { try { up = (await fetch(`http://localhost:${PORT}/`)).ok; } catch { await sleep(500); } }
  if (!up) throw new Error("preview server did not start");
  const browser = await chromium.launch();
  const ctx = await browser.newContext(); // fresh: no storage state, no cookies
  const page = await ctx.newPage();
  const hosts = new Set(); page.on("request", r => hosts.add(new URL(r.url()).host));
  await page.goto(`http://localhost:${PORT}/`, { waitUntil: "networkidle" });
  await page.waitForSelector(".hme h1");
  await page.waitForTimeout(1500);
  const ls = await page.evaluate(() => Object.keys(localStorage));
  if (ls.some(k => /auth|token|session|sb-/i.test(k))) throw new Error("auth-like localStorage key present: " + ls);
  const html = await page.evaluate(() => {
    const KEEP = new Set(["HEADER","NAV","MAIN","SECTION","FOOTER","H1","H2","H3","H4","P","A","UL","OL","LI","STRONG","B","EM","BR","BLOCKQUOTE","TIME"]);
    const DROP = "svg,img,script,style,noscript,iframe,video,button,input,form,[aria-hidden='true']";
    const esc = s => s.replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;");
    const attr = s => esc(s).replace(/"/g,"&quot;");
    const ser = n => {
      if (n.nodeType === 3) return esc(n.textContent.replace(/\s+/g, " "));
      if (n.nodeType !== 1 || n.matches(DROP)) return "";
      const inner = [...n.childNodes].map(ser).join("");
      if (!KEEP.has(n.tagName)) return n.tagName === "DIV" ? " " + inner + " " : inner;
      const t = n.tagName.toLowerCase();
      if (t === "br") return "<br>";
      if (t === "a") { const h = n.getAttribute("href") || ""; if (!/^(\/|#|https:\/\/|mailto:)/.test(h)) return inner; return `<a href="${attr(h)}">${inner.trim()}</a>`; }
      if (!inner.trim()) return "";
      const id = ["SECTION"].includes(n.tagName) && n.id ? ` id="${attr(n.id)}"` : "";
      return `<${t}${id}>${inner.trim()}</${t}>`;
    };
    return ser(document.querySelector(".hme")).replace(/ {2,}/g, " ").replace(/> </g, "><");
  });
  await browser.close();
  if (!html.includes("<h1>")) throw new Error("no h1 in snapshot");
  if (/eyJ[A-Za-z0-9_-]{10,}|supabase|service_role|sk_live|sk_test|localhost/i.test(html)) throw new Error("secret/internal pattern in snapshot");
  fs.writeFileSync(OUT, `<!-- generated by scripts/snapshot-home.mjs; do not edit -->\n<div id="seo-home" data-seo-snapshot>${html}</div>\n`);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${fs.statSync(OUT).size} bytes); hosts requested: ${[...hosts].join(", ")}`);
} finally { srv.kill(); }
